        NSString *pref = NSBundle.mainBundle.preferredLocalizations.firstObject
                      ?: NSLocale.preferredLanguages.firstObject ?: @"en";
        NSString *l = [[pref stringByReplacingOccurrencesOfString:@"_" withString:@"-"] lowercaseString];
        if ([l hasPrefix:@"zh"]) {
            BOOL trad = [l containsString:@"hant"] || [l hasSuffix:@"-tw"] || [l hasSuffix:@"-hk"] || [l hasSuffix:@"-mo"];
            lang = trad ? @"zh-Hant" : @"zh-Hans";
        } else {
            lang = [l componentsSeparatedByString:@"-"].firstObject ?: @"en";
            if ([lang isEqualToString:@"nb"] || [lang isEqualToString:@"no"]) lang = @"en";
        }
        if (!SLTables()[lang]) lang = @"en";
    });
    return lang;
}

NSString *SLLoc(NSString *key) {
    return SLTables()[SLLanguage()][key] ?: SLTables()[@"en"][key] ?: key;
}

NSString *SLLocFormat(NSString *key, ...) {
    va_list args;
    va_start(args, key);
    NSString *s = [[NSString alloc] initWithFormat:SLLoc(key) arguments:args];
    va_end(args);
    return s;
}
